import { HttpResponse, bypass, http, sse } from 'msw';
import { apiUrl } from '@/api/client';
import type { Document, DocumentDetail, Job, SearchSource, UploadAccepted } from '@/api/types';
import {
  JOB_ERROR,
  addDocument,
  createJob,
  currentDocument,
  db,
  jobDuration,
  nextDocumentId,
  startProcessing,
} from './db';
import {
  STEPS_BY_KIND,
  checkResult,
  checkSteps,
  compareResult,
  contradictionResult,
  queryResult,
} from './fixtures';
import { findChunk } from './papers';
import { scaledDelay, wait } from './settings';

const MAX_FILES = 5;
const MAX_BYTES = 25 * 1024 * 1024;
const ALL_SOURCES: SearchSource[] = [
  'semantic_scholar',
  'arxiv',
  'tavily',
  'vector_dense',
  'bm25_sparse',
  'uploaded_docs',
];

// Sample PDFs generated by scripts/make-sample-pdfs.ts (fictional content).
const PDF_URLS = import.meta.glob<string>('./pdfs/*.pdf', {
  query: '?url',
  import: 'default',
  eager: true,
});

function fail(status: number, code: string, message: string) {
  return HttpResponse.json({ error: { code, message } }, { status });
}

function readyDocuments(ids: unknown): Document[] | Response {
  if (!Array.isArray(ids) || ids.some((id) => typeof id !== 'string')) {
    return fail(400, 'INVALID_REQUEST', 'document_ids must be a list of document ids.');
  }
  const docs: Document[] = [];
  for (const id of ids as string[]) {
    const stored = db.documents.get(id);
    if (!stored) return fail(404, 'NOT_FOUND', `No document with id ${id}.`);
    const doc = currentDocument(stored);
    if (doc.status !== 'ready') {
      return fail(409, 'DOCUMENT_NOT_READY', `“${doc.title}” is not ready yet.`);
    }
    docs.push(doc);
  }
  return docs;
}

const titleFromFilename = (name: string) => {
  const base = name
    .replace(/\.pdf$/i, '')
    .replace(/[-_]+/g, ' ')
    .trim();
  return base ? base.charAt(0).toUpperCase() + base.slice(1) : 'Untitled paper';
};

/**
 * GET /jobs/{id}/stream as Server-Sent Events. MSW can only build it where EventSource exists
 * (the browser); in tests the app falls back to polling GET /jobs/{id}.
 */
function streamHandler() {
  return sse<{ step: string; done: string; error: string }>(
    apiUrl('/jobs/:id/stream'),
    ({ client, params }) => {
      const job = db.jobs.get(String(params.id));
      if (!job) {
        client.error();
        return;
      }
      void (async () => {
        for (const [index, step] of job.steps.entries()) {
          await wait(job.stepDelays[index] ?? 600);
          if (job.failAfter === index) {
            client.send({ event: 'error', data: JSON.stringify({ error: JOB_ERROR }) });
            client.close();
            return;
          }
          client.send({ event: 'step', data: JSON.stringify(step) });
        }
        await new Promise((resolve) => setTimeout(resolve, scaledDelay(300)));
        client.send({ event: 'done', data: JSON.stringify({ result: job.result }) });
        client.close();
      })();
    },
  );
}

export const handlers = [
  http.get(apiUrl('/health'), () =>
    HttpResponse.json({ status: 'ok', version: '0.1.0-mock', mock_ai: true }),
  ),

  // ---- Documents ------------------------------------------------------------------------------

  http.get(apiUrl('/documents'), ({ request }) => {
    const status = new URL(request.url).searchParams.get('status');
    const docs = [...db.documents.values()]
      .filter((stored) => stored.inLibrary)
      .map((stored) => currentDocument(stored))
      .filter((doc) => !status || doc.status === status);
    return HttpResponse.json(docs);
  }),

  http.get(apiUrl('/documents/:id'), ({ params }) => {
    const stored = db.documents.get(String(params.id));
    if (!stored) return fail(404, 'NOT_FOUND', 'Document not found.');
    const doc = currentDocument(stored);
    const detail: DocumentDetail = {
      document_id: doc.document_id,
      status: doc.status,
      pages: doc.pages,
      chunks: doc.chunks ?? 0,
      sections: stored.sections,
      error: doc.error ?? null,
    };
    return HttpResponse.json(detail);
  }),

  http.delete(apiUrl('/documents/:id'), ({ params }) => {
    if (!db.documents.delete(String(params.id)))
      return fail(404, 'NOT_FOUND', 'Document not found.');
    return new HttpResponse(null, { status: 204 });
  }),

  http.get(apiUrl('/documents/:id/file'), async ({ params }) => {
    const id = String(params.id);
    const stored = db.documents.get(id);
    if (!stored) return fail(404, 'NOT_FOUND', 'Document not found.');
    if (stored.file) {
      return HttpResponse.arrayBuffer(stored.file, {
        headers: { 'Content-Type': 'application/pdf' },
      });
    }
    // Papers without a generated sample (e.g. fetched by link) reuse the first sample.
    const url = PDF_URLS[`./pdfs/${id}.pdf`] ?? PDF_URLS['./pdfs/DOC001.pdf'];
    if (!url) return fail(404, 'NOT_FOUND', 'No sample PDF for this document.');
    const response = await fetch(bypass(new URL(url, window.location.href)));
    return HttpResponse.arrayBuffer(await response.arrayBuffer(), {
      headers: { 'Content-Type': 'application/pdf' },
    });
  }),

  /** Proposed endpoint: fetch a paper by arXiv / DOI / Semantic Scholar link. */
  http.post(apiUrl('/documents/fetch'), async ({ request }) => {
    const body = (await request.json()) as { url?: unknown };
    const url = typeof body.url === 'string' ? body.url.trim() : '';
    if (!/^https?:\/\/\S+$/i.test(url) && !/^10\.\d{4,}\//.test(url)) {
      return fail(400, 'INVALID_REQUEST', 'Enter an arXiv URL, DOI or Semantic Scholar link.');
    }
    await wait(400);
    const id = nextDocumentId();
    const stored = addDocument({
      document_id: id,
      title: `Fetched paper (${url.replace(/^https?:\/\/(www\.)?/, '').slice(0, 40)})`,
      filename: `${id}.pdf`,
      pages: 18,
      status: 'processing',
      source: 'link',
      url,
      uploaded_at: new Date().toISOString(),
    });
    return HttpResponse.json(stored.doc, { status: 202 });
  }),

  /** Proposed endpoint: re-index a failed paper with OCR. */
  http.post(apiUrl('/documents/:id/retry'), ({ params }) => {
    const stored = db.documents.get(String(params.id));
    if (!stored) return fail(404, 'NOT_FOUND', 'Document not found.');
    startProcessing(stored, 8_000);
    return HttpResponse.json(stored.doc, { status: 202 });
  }),

  http.post(apiUrl('/upload'), async ({ request }) => {
    const form = await request.formData();
    const files = form.getAll('files').filter((entry): entry is File => entry instanceof File);
    if (files.length === 0 || files.length > MAX_FILES) {
      return fail(400, 'INVALID_REQUEST', `Upload between 1 and ${MAX_FILES} PDFs.`);
    }
    for (const file of files) {
      if (!/\.pdf$/i.test(file.name) && file.type !== 'application/pdf') {
        return fail(415, 'UNSUPPORTED_TYPE', `${file.name} is not a PDF.`);
      }
      if (file.size > MAX_BYTES) return fail(413, 'FILE_TOO_LARGE', `${file.name} is over 25 MB.`);
    }
    const accepted: UploadAccepted[] = [];
    for (const file of files) {
      const id = nextDocumentId();
      const pages = 12 + (file.name.length % 18);
      addDocument(
        {
          document_id: id,
          title: titleFromFilename(file.name),
          filename: file.name,
          pages,
          chunks: pages * 7,
          status: 'processing',
          source: 'upload',
          uploaded_at: new Date().toISOString(),
        },
        await file.arrayBuffer(),
      );
      accepted.push({ document_id: id, filename: file.name, status: 'processing' });
    }
    return HttpResponse.json(accepted, { status: 202 });
  }),

  http.get(apiUrl('/chunks/:id'), ({ params }) => {
    const chunk = findChunk(String(params.id));
    return chunk ? HttpResponse.json(chunk) : fail(404, 'NOT_FOUND', 'Chunk not found.');
  }),

  // ---- Jobs -----------------------------------------------------------------------------------

  http.post(apiUrl('/check'), async ({ request }) => {
    const body = (await request.json()) as { claim?: unknown; sources?: unknown };
    const claim = typeof body.claim === 'string' ? body.claim.trim() : '';
    if (claim.length < 3) return fail(400, 'INVALID_REQUEST', 'Enter a claim to check.');
    const sources = Array.isArray(body.sources)
      ? ALL_SOURCES.filter((s) => (body.sources as unknown[]).includes(s))
      : ALL_SOURCES;
    if (sources.length === 0) return fail(400, 'INVALID_REQUEST', 'Choose at least one source.');
    const job = createJob(
      'check',
      checkSteps(sources),
      checkResult(claim, sources, new Date().toISOString()),
    );
    return HttpResponse.json({ job_id: job.id }, { status: 202 });
  }),

  http.post(apiUrl('/query'), async ({ request }) => {
    const body = (await request.json()) as { question?: unknown; document_ids?: unknown };
    const question = typeof body.question === 'string' ? body.question.trim() : '';
    if (!question) return fail(400, 'INVALID_REQUEST', 'Enter a question.');
    const docs = readyDocuments(body.document_ids);
    if (docs instanceof Response) return docs;
    if (docs.length === 0) return fail(400, 'INVALID_REQUEST', 'Choose at least one paper.');
    const job = createJob('query', STEPS_BY_KIND.query, queryResult(question));
    return HttpResponse.json({ job_id: job.id }, { status: 202 });
  }),

  http.post(apiUrl('/compare'), async ({ request }) => {
    const body = (await request.json()) as { document_ids?: unknown };
    const docs = readyDocuments(body.document_ids);
    if (docs instanceof Response) return docs;
    if (docs.length < 2) return fail(400, 'INVALID_REQUEST', 'Choose at least two papers.');
    const ids = docs.map((doc) => doc.document_id);
    const job = createJob('compare', STEPS_BY_KIND.compare, compareResult(ids));
    return HttpResponse.json({ job_id: job.id }, { status: 202 });
  }),

  http.post(apiUrl('/contradiction'), async ({ request }) => {
    const body = (await request.json()) as { document_ids?: unknown; topic?: unknown };
    const docs = readyDocuments(body.document_ids);
    if (docs instanceof Response) return docs;
    if (docs.length < 2) return fail(400, 'INVALID_REQUEST', 'Choose at least two papers.');
    const topic = typeof body.topic === 'string' ? body.topic : undefined;
    const job = createJob('contradiction', STEPS_BY_KIND.contradiction, contradictionResult(topic));
    return HttpResponse.json({ job_id: job.id }, { status: 202 });
  }),

  http.get(apiUrl('/jobs/:id'), ({ params }) => {
    const job = db.jobs.get(String(params.id));
    if (!job) return fail(404, 'NOT_FOUND', 'Job not found.');
    const finished = Date.now() - job.createdAt >= jobDuration(job);
    const body: Job = { job_id: job.id, kind: job.kind, status: 'running' };
    if (finished && job.failAfter !== undefined)
      Object.assign(body, { status: 'error', error: JOB_ERROR });
    else if (finished) Object.assign(body, { status: 'done', result: job.result });
    return HttpResponse.json(body);
  }),

  ...(typeof EventSource === 'undefined' ? [] : [streamHandler()]),
];
